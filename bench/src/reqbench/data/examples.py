"""Pick the few-shot examples shown to both Jev and the LLM, from the dev split only.

Examples are short (<= MAX_WORDS) and drawn with a fixed seed. Requirements involved in any
duplicate or near-duplicate pair are not eligible (their label may be contested). Example IDs
are recorded so that dev-set metrics can exclude them.
"""

import numpy as np
import pandas as pd
import yaml
from reqcore.paths import questions_dir

from reqbench.data.splits import SEED

PER_LEAF = 2
MAX_WORDS = 25
EXAMPLES_VERSION = "examples_v1"


def pick_examples(data: pd.DataFrame, splits: pd.DataFrame, ineligible: set[str]) -> dict:
    dev = data.merge(splits[["req_id", "split"]], on="req_id")
    dev = dev[
        (dev["split"] == "dev")
        & (dev["text"].str.split().str.len() <= MAX_WORDS)
        & ~dev["req_id"].isin(ineligible)
    ]
    rng = np.random.default_rng(SEED)
    examples: dict[str, list[str]] = {}
    ids: dict[str, list[str]] = {}
    for leaf, group in sorted(dev.groupby("leaf")):
        chosen = group.iloc[rng.choice(len(group), size=PER_LEAF, replace=False)]
        examples[leaf] = chosen["text"].tolist()
        ids[leaf] = chosen["req_id"].tolist()
    return {"version": EXAMPLES_VERSION, "seed": SEED, "source_ids": ids, "examples": examples}


def write_examples(spec: dict) -> None:
    path = questions_dir() / f"{EXAMPLES_VERSION}.yaml"
    header = (
        "# Generated by `reqbench data examples` from the dev split (never test).\n"
        "# Exclude `source_ids` from dev metrics.\n"
        "# Example texts are quoted from PROMISE NFR (Cleland-Huang et al., 2007), CC BY 4.0,\n"
        "# https://doi.org/10.5281/zenodo.268542. See DATA_LICENSES.md.\n"
    )
    path.write_text(header + yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=100))


def example_ids() -> set[str]:
    path = questions_dir() / f"{EXAMPLES_VERSION}.yaml"
    spec = yaml.safe_load(path.read_text(encoding="utf-8"))
    return {rid for ids in spec["source_ids"].values() for rid in ids}
